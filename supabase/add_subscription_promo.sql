-- ABONELİK + PROMO KOD ALTYAPISI — 2026-07-07
-- Kural: ücretsiz kullanım yok. İşletme, aboneliği (subscription_until)
-- geçerli olduğu sürece müşterilere görünür. Süreyi promo kod
-- (şimdilik) ve ödeme (iyzico bağlanınca) uzatır.
--
-- Görünürlük = onaylı (approval_status) VE aboneliği geçerli.
-- Promo kod üretme/yönetme: www.randezy.com/admin → Promo Kodlar.
-- ============================================================

-- 1) shops.subscription_until — erişim bu tarihe kadar geçerli.
--    Varsayılan now() => yeni kayıt "süresi dolmuş" başlar (ücretsiz yok).
alter table public.shops
  add column if not exists subscription_until timestamptz not null default now();

-- 2) TEK SEFERLİK backfill: mevcut pilot işletmelere 90 gün süre.
--    (Tarih guard'ı: script yanlışlıkla ikinci kez çalıştırılırsa
--     yeni kayıtlara süre dağıtmasın diye.)
update public.shops
   set subscription_until = now() + interval '90 days'
 where subscription_until <= now()
   and created_at < '2026-07-07T00:00:00Z';

-- 3) Promo kodlar
create table if not exists public.promo_codes (
  id            integer generated by default as identity primary key,
  code          text not null unique check (code ~ '^[A-Z0-9-]{4,24}$'),
  description   text,
  duration_days integer not null check (duration_days between 1 and 730),
  max_uses      integer check (max_uses is null or max_uses > 0),  -- null = sınırsız
  used_count    integer not null default 0,
  is_active     boolean not null default true,
  expires_at    timestamptz,                                        -- null = süresiz
  created_at    timestamptz not null default now()
);

-- 4) Kod kullanım kayıtları (ispat + tekrar kullanım engeli)
create table if not exists public.promo_redemptions (
  id             integer generated by default as identity primary key,
  promo_code_id  integer not null references public.promo_codes(id),
  shop_id        integer not null references public.shops(id) on delete cascade,
  granted_until  timestamptz not null,
  redeemed_at    timestamptz not null default now(),
  unique (promo_code_id, shop_id)
);

-- 5) RLS: iki tablo da kilitli — erişim yalnızca service_role API'leri
--    üzerinden (policy tanımlanmadığı için anon/authenticated hiçbir
--    satır okuyamaz/yazamaz; kod listesi dışarı sızmaz).
alter table public.promo_codes enable row level security;
alter table public.promo_redemptions enable row level security;

-- 6) Görünürlük kapısını güncelle: onay + geçerli abonelik.
--    İstisnalar: sahibi kendi işletmesini her zaman görür; randevusu
--    olan müşteri (geçmiş randevularının işletme adı kaybolmasın diye)
--    işletme kaydını okumaya devam edebilir.
--    ⚠️ Randevu kontrolü SECURITY DEFINER fonksiyonla yapılır — policy
--    içinde doğrudan appointments sorgusu SONSUZ DÖNGÜ yaratır (42P17),
--    çünkü appointments'ın RLS'i shops'a bakar. Değiştirme!
create or replace function public.user_has_appointment_at(p_shop_id integer)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.appointments a
    where a.shop_id = p_shop_id
      and a.user_id = auth.uid()
  );
$$;

revoke all on function public.user_has_appointment_at(integer) from public;
grant execute on function public.user_has_appointment_at(integer) to anon, authenticated;

drop policy if exists shops_approval_gate on public.shops;
drop policy if exists shops_visibility_gate on public.shops;
create policy shops_visibility_gate on public.shops
  as restrictive
  for select
  to public
  using (
    (approval_status = 'approved' and subscription_until > now())
    or owner_id = auth.uid()
    or public.user_has_appointment_at(id)
  );

-- 7) Policy'deki exists sorgusu için indeks
create index if not exists idx_appointments_shop_user
  on public.appointments (shop_id, user_id);

-- 8) Stripe abonelik bağlantısı (ödeme altyapısı)
alter table public.shops
  add column if not exists stripe_customer_id text,
  add column if not exists stripe_subscription_id text;
